// Service worker minimal : uniquement pour recevoir les notifications Web
// Push (nouvelle commande a confirmer, voir services/push_notifications.py
// cote backend). Pas de cache offline — pas necessaire pour un usage admin.

self.addEventListener("install", () => {
  self.skipWaiting();
});

self.addEventListener("activate", (event) => {
  event.waitUntil(self.clients.claim());
});

self.addEventListener("push", (event) => {
  let data = { title: "MYFACE", body: "Nouvelle notification", url: "/admin/events" };
  try {
    data = event.data.json();
  } catch {
    // payload non-JSON : garde les valeurs par defaut
  }

  event.waitUntil(
    self.registration.showNotification(data.title, {
      body: data.body,
      icon: "/icon-192.png",
      badge: "/icon-192.png",
      data: { url: data.url },
    })
  );
});

self.addEventListener("notificationclick", (event) => {
  event.notification.close();
  const url = event.notification.data?.url || "/admin/events";

  event.waitUntil(
    self.clients.matchAll({ type: "window", includeUncontrolled: true }).then((clients) => {
      for (const client of clients) {
        if (client.url === url && "focus" in client) return client.focus();
      }
      return self.clients.openWindow(url);
    })
  );
});
